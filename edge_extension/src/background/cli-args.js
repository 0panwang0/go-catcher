// 兜底命令的参数净化 + 输出文件名清洗 —— 全项目唯一实现。
// 使用方：downloader.js（ES 模块，直接 import）、content.js（经典脚本，经
// build.mjs 生成的 content-shared.js 注入，见那个文件头部说明）。
//
// ============================================================
// 为什么是「剔除」而不是「转义」
// ------------------------------------------------------------
// 兜底命令要能同时粘贴进 PowerShell 5.1 / cmd / Git Bash 运行，而这三家的
// 引号转义规则互不相容（PowerShell 用反引号、cmd 用 ^、bash 用反斜杠）。
// 按任一家加转义，都会在另两家变成一条坏命令 —— 那是用一个坏命令换另一个
// 坏命令。参数值本来也不需要这些字符：URL 由浏览器编码成 %22，标题只要
// 可读文本，路径里的引号是**用户从资源管理器复制地址时带进来的**（见下）。
// 直接剔除最稳，而且结果对三家 shell 都成立。
//
// 现实可达路径（评审 P2-8 / F9）：扩展设置页「go-catcher.exe 路径」输入框，
// 占位文案就写着"或填本机完整路径"。用户从资源管理器「复制文件地址」拿到的
// 是带双引号的字符串，粘进去后这一项变成 ""C:\Program Files\x.exe""：
// 那对空引号被解析成空串，真正的路径露出在引号外，被空白切成
// 「C:\Program」+「Files\x.exe」两个参数 —— 命令必然失败。而这是本地服务
// 没起来时用户唯一的兜底手段。整条命令的引号总数仍是偶数，所以「数引号
// 奇偶」不是判据；判据是「参数个数与结构不变」。
// ============================================================

// 控制字符：C0（\x00-\x1f，含换行 \n 与制表 \t）+ DEL + C1。
// 必须显式列出——`\s` 只覆盖空白类（\n \t \r \f \v 与 Unicode 空白），
// \x07（响铃）、\x1b（ESC）、\x00 会原样穿透进参数与文件名。
const CONTROL_CHARS = /[\u0000-\u001f\u007f-\u009f]/g;

// sanitizeFileName 把任意文本清洗成可用作文件名的形态：
//   1. 先剔控制字符（否则它们会参与后面几步的空白归并，产生奇怪的空隙）
//   2. Windows 非法字符逐个替换为下划线
//   3. 归并替换留下的碎屑："Bad/Name: with* x" → "Bad_Name_with_x"，
//      而不是 "Bad_Name_ with_ x"
// 注意第 3 步会把连续下划线压成一个 —— 这是有意为之：清洗后撞名的风险
// 与替换本身同源（"A/B" 与 "A:B" 在旧实现里也都会变成 "A_B"），
// 换来的是文件名里不会出现一串下划线。
export function sanitizeFileName(name) {
  return String(name == null ? "" : name)
    .replace(CONTROL_CHARS, "")
    .replace(/[\\/:*?"<>|]/g, "_")
    .replace(/_{2,}/g, "_")
    .replace(/\s*_\s*/g, "_")
    .replace(/\s+/g, " ")
    .replace(/^[_\s]+|[_\s]+$/g, "")
    .trim();
}

// quoteArg 把将被放进双引号里的参数值净化：剔除双引号与控制字符。
// 保留双引号包裹本身（bash 下不加引号会把位置参数按空白切片），
// 但值里绝不能再出现引号——奇数个就会让整个命令的引号配对错位。
export function quoteArg(v) {
  return String(v == null ? "" : v)
    .replace(CONTROL_CHARS, "")
    .replace(/"/g, "")
    .trim();
}
